#!/usr/bin/env bash
# Shared config + helpers for the anvil-devnet ops scripts.
# Sourced by install.sh / bootstrap.sh / caddy-add-user.sh / deploy.sh / reset.sh.
set -euo pipefail

# --- Foundry -----------------------------------------------------------------
FOUNDRY_DIR="${FOUNDRY_DIR:-/opt/foundry}"
FOUNDRY_BIN="${FOUNDRY_DIR}/bin"
ANVIL="${FOUNDRY_BIN}/anvil"
CAST="${FOUNDRY_BIN}/cast"
FORGE="${FOUNDRY_BIN}/forge"

# --- Anvil service -----------------------------------------------------------
ANVIL_USER="anvil"
ANVIL_HOME="/opt/anvil"
ANVIL_ENV="/etc/anvil/anvil.env"            # ANVIL_MNEMONIC=...  (mode 600, anvil:anvil)
STATE_DIR="/var/lib/anvil"
ANVIL_STATE="${STATE_DIR}/state.json"
DEPLOYMENTS_JSON="${STATE_DIR}/deployments.json"

# --- Chain -------------------------------------------------------------------
RPC_HOST="127.0.0.1"
RPC_PORT="8545"
RPC_URL="http://${RPC_HOST}:${RPC_PORT}"
CHAIN_ID="31337"

# --- Public edge -------------------------------------------------------------
PUBLIC_HOST="rpc-dev.decdn.org"
CADDY_BIND_PORT="8080"
CADDY_USERS_TSV="/etc/caddy/rpc-dev.users.tsv"     # username<TAB>bcrypt-hash registry
CADDY_BASICAUTH="/etc/caddy/rpc-dev.basicauth"     # generated import file for Caddyfile

# --- cloudflared -------------------------------------------------------------
CFD_USER="cloudflared"
CFD_DIR="/etc/cloudflared"

# --- Pretty logging ----------------------------------------------------------
log()  { printf '\033[1;34m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m[!]\033[0m %s\n'  "$*" >&2; }
die()  { printf '\033[1;31m[x]\033[0m %s\n'  "$*" >&2; exit 1; }

need_root() { [ "$(id -u)" -eq 0 ] || die "Must run as root (use sudo)."; }

# Block until the local anvil RPC answers, or fail after N seconds.
wait_for_rpc() {
	local tries="${1:-30}" i
	log "Waiting for anvil RPC at ${RPC_URL} ..."
	for ((i = 0; i < tries; i++)); do
		if "$CAST" block-number --rpc-url "$RPC_URL" >/dev/null 2>&1; then
			log "RPC is up (block $("$CAST" block-number --rpc-url "$RPC_URL"))."
			return 0
		fi
		sleep 1
	done
	die "anvil RPC did not become ready after ${tries}s. Check: journalctl -u anvil -e"
}

# Load the shared mnemonic into $ANVIL_MNEMONIC from the protected env file.
# Requires root (or the anvil user) because the file is mode 600.
read_mnemonic() {
	[ -r "$ANVIL_ENV" ] || die "Cannot read ${ANVIL_ENV}. Run as root, after bootstrap.sh."
	# shellcheck disable=SC1090
	set -a; . "$ANVIL_ENV"; set +a
	[ -n "${ANVIL_MNEMONIC:-}" ] || die "ANVIL_MNEMONIC not set in ${ANVIL_ENV}."
}

# Insert-or-replace a username->hash pair in the basic-auth registry (TSV).
upsert_basicauth_user() {
	local user="$1" hash="$2" tmp
	need_root
	install -d -m 750 -o root -g caddy "$(dirname "$CADDY_USERS_TSV")" 2>/dev/null || \
		install -d -m 750 "$(dirname "$CADDY_USERS_TSV")"
	[ -f "$CADDY_USERS_TSV" ] || { : > "$CADDY_USERS_TSV"; }
	tmp="$(mktemp)"
	awk -F '\t' -v u="$user" '$1 != u' "$CADDY_USERS_TSV" > "$tmp" || true
	printf '%s\t%s\n' "$user" "$hash" >> "$tmp"
	LC_ALL=C sort -o "$tmp" "$tmp"
	mv "$tmp" "$CADDY_USERS_TSV"
	chown root:caddy "$CADDY_USERS_TSV" 2>/dev/null || true
	chmod 640 "$CADDY_USERS_TSV"
}

# Rebuild the Caddy `basic_auth { ... }` import file from the TSV registry.
regenerate_basicauth() {
	need_root
	[ -f "$CADDY_USERS_TSV" ] || die "No users registry at ${CADDY_USERS_TSV}."
	{
		echo "# GENERATED by bin/caddy-add-user.sh from ${CADDY_USERS_TSV} — do not edit by hand."
		echo "basic_auth {"
		while IFS=$'\t' read -r u h; do
			[ -n "$u" ] || continue
			printf '\t%s %s\n' "$u" "$h"
		done < "$CADDY_USERS_TSV"
		echo "}"
	} > "$CADDY_BASICAUTH"
	chown root:caddy "$CADDY_BASICAUTH" 2>/dev/null || true
	chmod 640 "$CADDY_BASICAUTH"
}
